// MAILAI_SEARCH_FIXTURE=1 tests/workspace_preview.py; synthetic mail/model only.
const assert=require('node:assert/strict');
const {chromium,webkit}=require('playwright');
(async()=>{
 const browser=await(process.env.MAILAI_BROWSER==='webkit'?webkit:chromium).launch();
 try{
  const page=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'reduce'}),errors=[],requests=[],details=[];
  await page.addInitScript(()=>localStorage.setItem('mailai.onboarding.v2',JSON.stringify({deferred:true,mailboxDone:true,aiDone:true})));
  page.on('pageerror',error=>errors.push(error.message));
  page.on('request',request=>{
   if(request.url().endsWith('/api/assistant/ask-stream'))requests.push(request.postDataJSON());
   if(/\/api\/emails\/\d+$/.test(request.url()))details.push(request.url());
  });
  await page.goto(process.env.MAILAI_FIXTURE_URL||'http://127.0.0.1:18795');
  await page.locator('#app-preloader').waitFor({state:'hidden'});
  await page.evaluate(()=>setI18nLanguage(I18N_DEFAULT_LANG));
  await page.locator('#email-list .email-item').first().waitFor();
  await page.evaluate(async()=>{
   const config=await api('/api/system/config');
   if(!config.accounts.every(account=>account.user.endsWith('@example.test')))throw new Error('Isolated fixture required');
   await openAccountMailbox(_systemConfig.accounts[0].id,'inbox');
  });
  const rows=page.locator('#email-list .email-item');
  const firstId=await rows.first().getAttribute('data-id'),lastId=await rows.last().getAttribute('data-id');
  const focusedId=()=>page.evaluate(()=>document.activeElement?.dataset.id);
  await rows.first().focus();const before=details.length;
  await page.keyboard.press('ArrowDown');assert.equal(await focusedId(),await rows.nth(1).getAttribute('data-id'));
  await page.keyboard.press('End');assert.equal(await focusedId(),lastId);
  await page.keyboard.press('Home');assert.equal(await focusedId(),firstId);
  assert.equal(details.length,before,'Browsing focus must not load or mark messages read');
  await page.keyboard.press('Enter');await page.waitForFunction(id=>selectedEmailId===Number(id)&&selectedEmailDetail,firstId);
  await rows.first().focus();await page.keyboard.press('Shift+F10');
  const menu=page.locator('#mail-context-menu');await menu.waitFor();
  await page.keyboard.press('ArrowDown');assert.equal(await page.evaluate(()=>document.activeElement.dataset.contextAction),'reply');
  await page.keyboard.press('End');assert.equal(await page.evaluate(()=>document.activeElement.dataset.contextAction),'select-all');
  await menu.locator('[data-context-action=folders]').focus();await page.keyboard.press('ArrowRight');
  assert.equal(await menu.locator('[data-context-action=folders]').getAttribute('aria-expanded'),'true');
  assert(await page.evaluate(()=>Boolean(document.activeElement.closest('.mail-context-folders'))));
  await page.keyboard.press('Escape');assert(await menu.isVisible());
  assert.equal(await page.evaluate(()=>document.activeElement.dataset.contextAction),'folders');
  await page.keyboard.press('Enter');await page.keyboard.press('Escape');
  assert(await menu.isVisible(),'Escape collapses folders opened with Enter before closing the menu');
  assert.equal(await menu.locator('[data-context-action=folders]').getAttribute('aria-expanded'),'false');
  await page.evaluate(()=>{emailListRenderSignature='';applyFilters({silent:true});});
  await page.keyboard.press('Escape');await menu.waitFor({state:'hidden'});
  assert.equal(await focusedId(),firstId);assert.equal(await page.evaluate(()=>selectedMailIds.size),1,'Closing the menu preserves selection');
  await page.keyboard.press('Escape');assert.equal(await page.evaluate(()=>selectedMailIds.size),0);
  await rows.first().press('Shift+F10');await page.locator('#global-search').click();
  assert.equal(await page.locator('#global-search').evaluate(input=>input===document.activeElement),true,'Outside clicks retain their own focus');
  await rows.first().press('Shift+F10');
  await page.locator('#email-list').evaluate(list=>list.dispatchEvent(new Event('scroll')));
  assert(await menu.isVisible(),'A delayed scroll event without movement keeps the new menu open');
  await page.locator('#email-list').evaluate(list=>{list.scrollTop+=80;});
  await menu.waitFor({state:'hidden'});
  for(const width of [1440,390]){
   await page.setViewportSize({width,height:600});
   await page.evaluate(async()=>{document.body.style.zoom=1.2;document.documentElement.style.setProperty('--fz','1.2');await new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve)));});
   await page.evaluate(id=>{selectedMailIds.add(Number(id));showMailContextMenu(innerWidth-2,innerHeight-2,Number(id));},firstId);
   await menu.locator('[data-context-action=folders]').focus();await page.keyboard.press('ArrowRight');
   const geometry=await menu.evaluate(node=>{const r=node.getBoundingClientRect();return{fits:r.left>=7&&r.top>=7&&r.right<=innerWidth-7&&r.bottom<=innerHeight-7,rect:r.toJSON(),width:innerWidth,height:innerHeight};});
   assert(geometry.fits,'Expanded menus fit narrow windows at zoom: '+JSON.stringify(geometry));
   await page.screenshot({path:`build/keyboard-menu-${process.env.MAILAI_BROWSER||'chromium'}-${width}.png`});
   await page.evaluate(()=>hideMailContextMenu());
  }
  await page.setViewportSize({width:1440,height:1000});
  await page.evaluate(()=>{document.body.style.zoom=1;document.documentElement.style.setProperty('--fz','1');clearMailSelection();_systemConfig.model={..._systemConfig.model,available:true,verified:true};});
  await page.locator('#global-search').fill('找检索同事最近一周的闭环合同');
  await page.waitForFunction(()=>mailSearchState.phase==='done');
  await page.locator('[data-search-recover=assistant]').click();
  const latest=()=>page.locator('.assistant-search-result').last();
  const ready=()=>page.waitForFunction(()=>!assistantController&&document.getElementById('mail-assistant').dataset.answerComplete==='true');
  await ready();const count=requests.length;
  await latest().locator('[data-search-edit=set_sender]').click();
  assert.equal(await latest().locator('.assistant-search-clue input').inputValue(),'检索同事');
  assert.equal(await latest().locator('[data-search-edit=set_sender]').getAttribute('aria-expanded'),'true');
  await page.keyboard.press('Escape');
  assert.equal(await page.evaluate(()=>document.activeElement.dataset.searchEdit),'set_sender');
  assert.equal(requests.length,count);
  await latest().locator('[data-search-edit=set_sender]').click();
  await latest().locator('.assistant-search-clue input').press('Enter');
  assert.equal(await latest().locator('.assistant-search-clue').isVisible(),false);
  assert.equal(requests.length,count,'Unchanged filters do not launch a new search');
  await latest().locator('[data-search-edit=set_sender]').click();
  await latest().locator('.assistant-search-clue input').fill('完全不存在的同事');
  await latest().locator('.assistant-search-clue input').press('Enter');await ready();
  assert.equal(requests.at(-1).search_action,'set_sender');
  assert.equal(requests.at(-1).search_value,'完全不存在的同事');
  assert.equal(await latest().locator('[data-search-loop-source]').count(),0);
  assert.match(await latest().locator('.assistant-search-conditions').innerText(),/闭环合同/,'Editing the sender preserves content filters');
  await latest().locator('[data-search-loop-action=undo]').click();await ready();
  assert.equal(await latest().locator('[data-search-loop-source]').count(),20);
  await latest().locator('[data-search-edit=set_keywords]').click();
  assert.equal(await latest().locator('.assistant-search-clue input').inputValue(),'闭环合同');
  await latest().locator('.assistant-search-clue input').fill('合同');
  await latest().locator('.assistant-search-clue input').press('Enter');await ready();
  assert.equal(requests.at(-1).search_action,'set_keywords');
  assert.match(await latest().locator('[data-search-edit=set_sender]').innerText(),/检索同事/);
  const candidates=()=>latest().locator('[data-search-source-details]:visible');
  await candidates().first().focus();const priorDetails=details.length;
  await page.keyboard.press('ArrowDown');assert.equal(await candidates().nth(1).evaluate(button=>button===document.activeElement),true);
  await page.keyboard.press('End');assert.equal(await candidates().nth(2).evaluate(button=>button===document.activeElement),true,'Hidden candidates are skipped');
  await latest().locator('[data-search-loop-more]').click();
  await candidates().first().focus();await page.keyboard.press('End');
  assert.equal(await candidates().last().evaluate(button=>button===document.activeElement),true);
  assert.equal(details.length,priorDetails,'Candidate keyboard navigation does not open mail');
  await latest().locator('[data-search-edit=set_sender]').click();
  const clue=latest().locator('.assistant-search-clue input');await clue.fill('尚未提交的发件人');
  await clue.evaluate(node=>node.setSelectionRange(2,5));const beforeLanguage=requests.length;
  await page.evaluate(()=>setI18nLanguage('en'));
  assert.equal(await clue.inputValue(),'尚未提交的发件人');assert(await clue.isVisible());
  assert(await clue.evaluate(node=>node===document.activeElement&&node.selectionStart===2&&node.selectionEnd===5));
  assert.equal(requests.length,beforeLanguage,'Changing language preserves the draft without submitting a search');
  assert.equal(await latest().locator('[data-search-edit=set_sender]').getAttribute('aria-label'),'Edit sender filter');
  await page.evaluate(()=>setI18nLanguage(I18N_DEFAULT_LANG));
  await clue.press('Escape');assert(await latest().locator('[data-search-edit=set_sender]').evaluate(node=>node===document.activeElement));
  await page.setViewportSize({width:390,height:1000});
  await page.evaluate(()=>{applyTheme('dark');document.body.style.zoom=1.2;document.documentElement.style.setProperty('--fz','1.2');mailaiAssistantSearch.focusLatest();});
  assert(await latest().evaluate(node=>node.scrollWidth<=node.clientWidth+1));
  await latest().locator('[data-search-edit=set_keywords]').click();
  assert.equal(await latest().locator('.assistant-search-clue input').inputValue(),'合同');
  await page.screenshot({path:`build/editable-search-${process.env.MAILAI_BROWSER||'chromium'}-390.png`});
  assert.deepEqual(errors,[]);
  console.log('PASS mail/candidate keyboard navigation, nested menu dismissal/focus, zoom placement, prefilled editable clues, no-op cancel, deterministic refinement and undo');
 }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
